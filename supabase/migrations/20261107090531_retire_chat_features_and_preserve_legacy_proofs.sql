  END IF;
  IF to_regclass('public.private_conversations') IS NOT NULL THEN
    EXECUTE 'DROP TRIGGER IF EXISTS private_conversations_validate_insert ON public.private_conversations';
    EXECUTE 'REVOKE ALL PRIVILEGES ON TABLE public.private_conversations FROM PUBLIC, anon, authenticated';
  END IF;
  IF to_regclass('public.private_messages') IS NOT NULL THEN
    EXECUTE 'DROP TRIGGER IF EXISTS private_messages_validate_insert ON public.private_messages';
    EXECUTE 'REVOKE ALL PRIVILEGES ON TABLE public.private_messages FROM PUBLIC, anon, authenticated';
  END IF;
  FOREACH table_name IN ARRAY ARRAY['p4_p5_p6_chat_messages','p5_p6_chat_messages','private_chat_hidden']
  LOOP
    IF to_regclass(format('public.%I',table_name)) IS NOT NULL THEN
      EXECUTE format('REVOKE ALL PRIVILEGES ON TABLE public.%I FROM PUBLIC, anon, authenticated',table_name);
    END IF;
  END LOOP;
END;
$retire$;

