        table_name,table_name
      );
      EXECUTE format(
        'INSERT INTO webkas_chat_rollback_20261107.%I SELECT * FROM public.%I ON CONFLICT DO NOTHING',
        table_name,table_name
      );
    END IF;
  END LOOP;

  INSERT INTO webkas_chat_rollback_20261107.rollback_metadata(object_type,object_name,definition)
  SELECT 'policy',schemaname||'.'||tablename||'.'||policyname,
         format('cmd=%s; roles=%s; qual=%s; with_check=%s',cmd,roles,coalesce(qual,''),coalesce(with_check,''))
  FROM pg_policies
  WHERE schemaname='public'
    AND tablename IN ('chat_messages','p4_p5_p6_chat_messages','p5_p6_chat_messages','private_chat_hidden','private_conversations','private_messages')
    AND NOT EXISTS (
      SELECT 1 FROM webkas_chat_rollback_20261107.rollback_metadata m
      WHERE m.object_type='policy'
        AND m.object_name=schemaname||'.'||tablename||'.'||policyname
    );

  INSERT INTO webkas_chat_rollback_20261107.rollback_metadata(object_type,object_name,definition)
  SELECT 'function',n.nspname||'.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')',pg_get_functiondef(p.oid)
  FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
  WHERE p.prokind='f'
    AND (p.proname ILIKE '%chat%' OR p.proname ILIKE '%private_message%' OR p.proname ILIKE '%private_conversation%')
    AND NOT EXISTS (
      SELECT 1 FROM webkas_chat_rollback_20261107.rollback_metadata m
      WHERE m.object_type='function'
        AND m.object_name=n.nspname||'.'||p.proname||'('||pg_get_function_identity_arguments(p.oid)||')'
    );
END;
