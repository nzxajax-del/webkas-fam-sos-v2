-- Optimize member leave request RLS initplans and add covering indexes for foreign keys.
DROP POLICY IF EXISTS member_leave_requests_insert_self_active ON public.member_leave_requests;
CREATE POLICY member_leave_requests_insert_self_active
ON public.member_leave_requests
FOR INSERT TO authenticated
WITH CHECK (
  member_id = (SELECT auth.uid())
  AND EXISTS (
    SELECT 1 FROM public.member_profiles p
    WHERE p.id = (SELECT auth.uid()) AND p.status = 'active'
  )
);

DROP POLICY IF EXISTS member_leave_requests_select_all_active_members ON public.member_leave_requests;
CREATE POLICY member_leave_requests_select_all_active_members
ON public.member_leave_requests
FOR SELECT TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.member_profiles viewer
    WHERE viewer.id = (SELECT auth.uid()) AND viewer.status = 'active'
  )
);

CREATE INDEX IF NOT EXISTS app_branding_settings_updated_by_idx
ON public.app_branding_settings(updated_by);
CREATE INDEX IF NOT EXISTS information_messages_sender_id_idx
ON public.information_messages(sender_id);

